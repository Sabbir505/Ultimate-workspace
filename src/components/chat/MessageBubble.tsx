/** Row of clickable chips for the files an assistant message produced. */
function MessageArtifacts({
  artifacts,
  onPreviewArtifact,
}: {
  artifacts: ChatArtifact[];
  onPreviewArtifact?: (artifact: ChatArtifact) => void;
}) {
  return (
    <div className="chat-msg-artifacts" aria-label="Generated files">
      {artifacts.map((a) => (
        <button
          key={a.path}
          type="button"
          className="chat-artifact-chip"
          title={`Preview ${a.filename}`}
          onClick={(e) => {
            e.currentTarget.blur();
            onPreviewArtifact?.(a);
          }}
        >
          <FileIcon />
          <span>{a.filename}</span>
        </button>
      ))}
    </div>
  );
}

/** Per-message action bar (Claude-style icons): copy for every message, edit
 *  for user messages, regenerate for assistant messages. Appears on hover
 *  under the bubble. */
function MessageActions({
  content,
  onEdit,
  onRepeat,
}: {
  content: string;
  onEdit?: (content: string) => void;
  onRepeat?: () => void;
}) {
  const [copied, setCopied] = useState(false);
  const copy = useCallback(
    async (e: React.MouseEvent<HTMLButtonElement>) => {
      // Drop focus so the hover-only action bar doesn't stay pinned open
      // after a mouse click.
      e.currentTarget.blur();
      try {
        await navigator.clipboard.writeText(content);
        setCopied(true);
        setTimeout(() => setCopied(false), 1800);
      } catch {
        // Clipboard unavailable — silently ignore.
      }
    },
    [content],
  );

  return (
    <div className="chat-msg-actions">
      <button
        className="chat-msg-action"
        onClick={copy}
        title={copied ? "Copied" : "Copy message"}
        aria-label="Copy message"
      >
        {copied ? <CheckIcon /> : <CopyIcon />}
      </button>
      {onRepeat && (
        <button
          className="chat-msg-action"
          onClick={(e) => {
            e.currentTarget.blur();
            onRepeat();
          }}
          title="Regenerate response"
          aria-label="Regenerate response"
        >
          <RepeatIcon />
        </button>
      )}
      {onEdit && (
        <button
          className="chat-msg-action"
          onClick={(e) => {
            e.currentTarget.blur();
            onEdit(content);
          }}
          title="Edit message"
          aria-label="Edit message"
        >
          <EditIcon />
        </button>
      )}
    </div>
  );
}

