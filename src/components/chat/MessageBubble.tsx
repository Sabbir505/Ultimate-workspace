interface Props {
  message: ChatMessage;
  /** True for the in-progress streaming bubble — hides the action bar. */
  live?: boolean;
  /** When provided (user messages), shows an "Edit" action that opens an inline
   *  editor; calling it submits the edited content (edit-to-fork). */
  onEdit?: (newContent: string) => void;
  /** When provided (assistant messages), shows a "Regenerate" action. */
  onRepeat?: () => void;
  /** When provided, shows a "Delete" action that removes this message from
   *  the chat (both locally and on the backend). Available on every non-
   *  live, non-system bubble (user and assistant alike). */
  onDelete?: () => void;
  /** Applies the "previous version" className to a row in a retired branch
   *  (roadmap #9). True when `message.supersededBy` is set. */
  superseded?: boolean;
  /** True when this row begins a new retired segment (the first superseded row
   *  after an active one) — renders the "— edited —" divider above it. */
  segmentStart?: boolean;
  /** Artifacts generated by this message, shown as clickable chips below it. */
  artifacts?: ChatArtifact[];
  /** Open an artifact in the preview pane (used by the inline chips). */
  onPreviewArtifact?: (artifact: ChatArtifact) => void;
  /** Numeric message id, emitted as `data-msg-id` on the root bubble so the
   *  TurnNavigator can scroll to it. Omitted on the live streaming bubble. */
  msgId?: number;
  /** Active chat session id — lets the compaction marker fetch the folded
   *  turns for its context-recovery disclosure. Omitted on the live bubble. */
  chatSessionId?: string | null;
  /** Live perf snapshot (elapsedMs, etc.) from `chat:perf` for the streaming
   *  bubble — used to show "Working for Xs" while the turn is in flight. */
  livePerf?: ChatPerfPayload | null;
  /** One-shot entrance animation. The bubble CSS animation must NOT run on
   *  every mount — virtualized rows remount on every scroll, and an animated
   *  remount reads as flicker (plus per-row paint work). ChatView sets this
   *  only for the row that was just appended. */
  enter?: boolean;
}

